test('import-as-new carries folders and retains unmatched legacy shortcuts', () => {
  h.freshStorage()
  const legacy = require('../src/utils/legacyImport.ts')
  const raw = JSON.stringify({songs:[{title:'Known',artist:'A',rawContent:'Lyrics'}],folders:tree,setlists:[{name:'Legacy',folderId:'b',songs:[{title:'Known',artist:'A'},{title:'Unknown'}]}]})
  const preview = legacy.previewBackupImport(raw)
  assert.equal(preview.isValid,true,preview.error)
  const result = legacy.confirmImportAsNew(preview,{songs:[],setlists:[],folders:[]},()=>true)
  assert.equal(result.isValid,true,result.error)
  assert.equal(result.setlists[0].songs.length,2)
  assert.equal(result.setlists[0].songs[0].id,result.songs[0].id)
  assert.notEqual(result.setlists[0].songs[1].id,result.songs[0].id)
  assert.equal(result.setlists[0].folderId,result.folders[1].id)
  assert.equal(result.folders[1].parentId,result.folders[0].id)
})
