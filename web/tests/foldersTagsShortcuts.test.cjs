test('folders use B3 records and the revision guard, survive reload and unfile atomically', async () => {
  const storage = h.freshStorage(), factory = new h.Factory()
  const tab = h.newTab()
  await tab.sj.prepareLibraryStorage(storage, {factory})
  const lib = {...h.library(2,1), folders:tree}
  lib.setlists[0].folderId = 'a'
  tab.sj.persistLibrary(lib, storage, {expectedRaw:tab.sj.libraryRevision(storage)})
  await tab.store.flushLibraryStore()
  assert.equal(factory.dump('gtar_library_db','folders').length, 2)
  const other = h.newTab()
  await other.sj.prepareLibraryStorage(storage, {factory})
  const back = other.sj.readPersistedLibrary(storage)
  assert.deepEqual(back.folders, tree)
  const revision = other.sj.libraryRevision(storage)
  other.sj.persistLibrary({...back,...folders.deleteSetlistFolder(back.folders,back.setlists,'a')}, storage, {expectedRaw:revision})
  await other.store.flushLibraryStore()
  assert.throws(()=>other.sj.persistLibrary(back,storage,{expectedRaw:revision}), /another tab/)
  assert.equal(other.sj.readPersistedLibrary(storage).setlists[0].folderId, null)
})
test('backup round trip retains folders, repeated shortcuts and missing songs; old backup imports', () => {
  h.freshStorage()
  const backup = require('../src/utils/jsonBackup.ts')
  const lib = h.library(2,1)
  lib.setlists[0].folderId = 'a'
  lib.setlists[0].songs.push({title:'Unmatched'})
  const payload = backup.createBackupPayload(lib.songs,lib.setlists,'test',undefined,tree)
  const parsed = backup.parseBackupJson(JSON.stringify(payload))
  assert.equal(parsed.isValid,true,parsed.error)
  assert.deepEqual(parsed.folders,tree)
  assert.equal(parsed.setlists[0].folderId,'a')
  assert.equal(parsed.setlists[0].songs.length,3)
  assert.equal(backup.verifyBackupJson(JSON.stringify(payload),payload).setlists,1)
  const old = backup.parseBackupJson(JSON.stringify({songs:lib.songs,setlists:lib.setlists}))
  assert.equal(old.isValid,true,old.error)
  assert.equal(old.setlists[0].songs.length,3)
})
test('pre-S4 v2 fingerprint verifies before shortcut upgrade', () => {
  h.freshStorage()
  const backup = require('../src/utils/jsonBackup.ts')
  const {cyrb53} = require('../src/utils/contentHash.ts')
  const song = {...backup.normalizeBackupSong({...h.library(1,0).songs[0], tags:['#Rock','LIVE']}), tags:['#Rock','LIVE']}
  const setlists = [{id:'legacy',name:'Legacy',songs:[{id:song.id,title:song.title,artist:song.artist}]}]
  const data = {schemaVersion:2, songs:[song], setlists, contentFingerprint:`c53:${cyrb53(JSON.stringify([[song],setlists]))}`}
  const parsed = backup.parseBackupJson(JSON.stringify(data))
  assert.equal(parsed.isValid,true,parsed.error)
  assert.ok(parsed.setlists[0].songs[0].entryId)
  assert.equal(backup.parseBackupJson(JSON.stringify({...data,songs:[{...song,rawContent:'tampered'}]})).isValid,false)
})

