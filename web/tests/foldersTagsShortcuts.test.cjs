const { test } = require('node:test')
const assert = require('node:assert/strict')
const h = require('./helpers/tabHarness.cjs')
const folders = require('../src/utils/folders.ts')
const tree = [{ id: 'a', name: 'A', parentId: null }, { id: 'b', name: 'B', parentId: 'a' }]
test('folder hierarchy rejects self, descendant and missing parents; delete unfiles setlists', () => {
  assert.equal(folders.validateFolderParentChange(tree, 'a', 'b'), false)
  assert.equal(folders.validateFolderParentChange(tree, 'a', 'a'), false)
  assert.equal(folders.validateFolderParentChange(tree, 'a', 'missing'), false)
  assert.equal(folders.buildFolderTree(tree)[0].children[0].folder.id, 'b')
  const result = folders.deleteSetlistFolder(tree, [{id:'s', name:'Set', folderId:'a', songs:[]}], 'a')
  assert.equal(result.setlists[0].folderId, null)
  assert.equal(result.folders[0].parentId, null)
  assert.equal(result.setlists.length, 1)
})
test('legacy shortcuts upgrade once, retain unmatched entries, and resolve library edits by id', () => {
  const s = require('../src/utils/setlistSongs.ts')
  const songs = h.library(2, 0).songs.map((song, i) => ({...song, id:`song-${i}`, title:'Same', artist:i ? 'B' : 'A'}))
  const [list] = s.bindLegacySetlists([{id:'set', name:'Set', songs:[{title:'Same',artist:'B'}, {title:'Same'}, {title:'Missing'}]}], songs)
  assert.equal(list.songs[0].id, 'song-1')
  assert.equal(list.songs[1].id, 'song-0')
  assert.equal(list.songs.length, 3)
  assert.ok(list.songs[2].id)
  assert.equal(s.resolveSetlistSong(list.songs[2], songs), undefined)
  assert.equal(new Set(list.songs.map(ref=>ref.entryId)).size, 3)
  assert.deepEqual(list.songs.map(ref=>ref.position), [0,1,2])
  assert.deepEqual(s.bindLegacySetlists([list], songs)[0], list)
  const edited = songs.map(song=>({...song,title:'Edited',artist:'Updated'}))
  assert.equal(s.resolveSetlistSong(list.songs[0], edited).title, 'Edited')
  assert.equal(s.resolveSetlistSong(list.songs[0], []), undefined)
  assert.equal(s.resolveSetlistSong(list.songs[0], songs).artist, 'B')
  assert.equal(s.transitionSongLibrary({active:[],deleted:songs,setlists:[list]}, {kind:'empty'}).setlists[0].songs.length, 3)
})
